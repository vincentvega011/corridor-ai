"""Generate frontend/lib/contracts.ts from the Python API contract (docs/spec/contracts.md, ADR 0016).

    make contracts          # writes frontend/lib/contracts.ts
    make contracts-check    # fails when the checked in file is out of date (also run by make test)

The TypeScript types are generated from the Pydantic models' JSON Schema, offline, with no Node tooling:
the file is never edited by hand. Money in these types is integer minor units (``number``) or display text
(``string``); there are no floats in any contract. Only the JSON Schema subset Pydantic emits for our
models is handled; anything else raises, so a new construct is noticed instead of silently mistyped.
"""

import json
import sys
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "lib" / "contracts.ts"
sys.path.insert(0, str(ROOT / "backend" / "src"))

from corridor.contracts.api import API_MODELS, EVENT_DATA_MODELS  # noqa: E402
from corridor.contracts.events import AgentEvent  # noqa: E402
from corridor.contracts.money import Money  # noqa: E402

HEADER = """// GENERATED by scripts/gen_contracts_ts.py from backend/src/corridor/contracts. DO NOT EDIT BY HAND.
// Regenerate with `make contracts`. Money is integer minor units (number) or display text (string); no floats.
// Event `data` types: see EventDataByType below; a client must ignore keys it does not know.
"""


def ts_type(node: dict[str, Any]) -> str:
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1]
    if "const" in node:
        return json.dumps(node["const"])
    if "enum" in node:
        return " | ".join(json.dumps(v) for v in node["enum"])
    if "anyOf" in node or "oneOf" in node:
        parts = [ts_type(n) for n in node.get("anyOf", node.get("oneOf", []))]
        return " | ".join(dict.fromkeys(parts))
    kind = node.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in node:
            return "[" + ", ".join(ts_type(n) for n in node["prefixItems"]) + "]"
        inner = ts_type(node.get("items", {}))
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if kind == "object":
        extra = node.get("additionalProperties")
        if node.get("properties"):
            return render_object(node)
        if isinstance(extra, dict):
            return f"Record<string, {ts_type(extra)}>"
        return "Record<string, unknown>"
    if not node:
        return "unknown"
    raise ValueError(f"unsupported JSON Schema node: {node}")


def render_object(node: dict[str, Any]) -> str:
    req = set(node.get("required", []))
    lines = []
    for name, sub in node.get("properties", {}).items():
        opt = "" if name in req else "?"
        doc = f"  /** {sub['description']} */\n" if sub.get("description") else ""
        lines.append(f"{doc}  {name}{opt}: {ts_type(sub)};")
    return "{\n" + "\n".join(lines) + "\n}"


def render() -> str:
    models = [*API_MODELS, AgentEvent, Money]
    _, schema = models_json_schema(
        [(m, "validation") for m in models], ref_template="#/$defs/{model}"
    )
    defs: dict[str, dict[str, Any]] = schema["$defs"]
    out = [HEADER]
    for name in sorted(defs):
        node = defs[name]
        if "enum" in node and node.get("type") == "string":
            out.append(f"export type {name} = {ts_type(node)};\n")
        elif node.get("type") == "object" and node.get("properties") is not None:
            doc = f"/** {node['description'].splitlines()[0]} */\n" if node.get("description") else ""
            out.append(f"{doc}export interface {name} {render_object(node)}\n")
        else:
            out.append(f"export type {name} = {ts_type(node)};\n")
    names = ", ".join(f'"{k}": {v.__name__}' for k, v in sorted(EVENT_DATA_MODELS.items()))
    out.append(f"export interface EventDataByType {{ {names.replace(', ', '; ')} }}\n")
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("frontend/lib/contracts.ts is out of date: run `make contracts`")
            return 1
        print("frontend/lib/contracts.ts is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
